"""Builds the Nifty 50 part of the watchlist from the NSE constituents file.

Pure functions only (no network, no SDK): the caller passes ICICI's NSE instrument list
(app.feeds.breeze_feed.nse_scrip_master()). scripts/update_watchlist.py ties them together.

A symbol is mapped only when the instrument list has exactly one EQ row whose NSE symbol
(ExchangeCode) matches and, when the constituents file gives an ISIN, whose ISIN matches too.
Anything else is reported as unmapped and left out. Codes are never guessed.
"""
from __future__ import annotations

import csv
import io
import json
from dataclasses import dataclass
from pathlib import Path

import yaml

from .config import Settings

BEGIN = "  # >>> nifty50: generated by scripts/update_watchlist.py from data/nifty50.csv - do not edit by hand"
END = "  # <<< nifty50"
REQUIRED_COLUMNS = ("Company Name", "Industry", "Symbol")


@dataclass(frozen=True)
class Constituent:
    company: str
    industry: str
    symbol: str
    isin: str | None


@dataclass(frozen=True)
class Mapped:
    symbol: str
    breeze_code: str
    sector: str
    company: str


def read_constituents(text: str) -> list[Constituent]:
    """Parse the niftyindices.com constituents CSV (Company Name, Industry, Symbol, Series, ISIN Code)."""
    reader = csv.DictReader(io.StringIO(text.lstrip("﻿")))
    header = [h.strip() for h in (reader.fieldnames or [])]
    missing = [c for c in REQUIRED_COLUMNS if c not in header]
    if missing:
        raise ValueError(f"constituents file is missing column(s) {missing}; found {header}")
    out: list[Constituent] = []
    seen: set[str] = set()
    for n, raw in enumerate(reader, start=2):
        row = {(k or "").strip(): (v or "").strip() for k, v in raw.items()}
        sym = row["Symbol"].upper()
        if not sym:
            raise ValueError(f"row {n}: empty Symbol")
        if not row["Industry"]:
            raise ValueError(f"row {n} ({sym}): empty Industry")
        if sym in seen:
            raise ValueError(f"row {n}: {sym} appears twice")
        seen.add(sym)
        out.append(Constituent(row["Company Name"], row["Industry"], sym, row.get("ISIN Code") or None))
    if not out:
        raise ValueError("constituents file has no rows")
    return out


def map_constituents(constituents: list[Constituent], scrip_rows: list[dict[str, str]]
                     ) -> tuple[list[Mapped], list[tuple[str, str]]]:
    """Return (mapped, unmapped as (symbol, reason)), both in file order."""
    by_symbol: dict[str, list[dict[str, str]]] = {}
    for r in scrip_rows:
        if r.get("Series", "").upper() == "EQ":
            by_symbol.setdefault(r.get("ExchangeCode", "").upper(), []).append(r)
    mapped: list[Mapped] = []
    unmapped: list[tuple[str, str]] = []
    for c in constituents:
        rows = by_symbol.get(c.symbol, [])
        if not rows:
            unmapped.append((c.symbol, "no EQ row with this NSE symbol in the Breeze instrument list"))
            continue
        if c.isin:
            rows = [r for r in rows if r.get("ISINCode", "").upper() == c.isin.upper()]
            if not rows:
                unmapped.append((c.symbol, f"instrument list has the symbol but not ISIN {c.isin}"))
                continue
        codes = sorted({r.get("ShortName", "") for r in rows})
        if len(codes) != 1 or not codes[0]:
            unmapped.append((c.symbol, f"ambiguous or empty Breeze code {codes}"))
            continue
        mapped.append(Mapped(c.symbol, codes[0], c.industry, c.company))
    return mapped, unmapped


def render_block(mapped: list[Mapped]) -> str:
    """YAML lines for the generated block, markers included. Values are JSON-quoted (valid YAML)
    so symbols like M&M and sectors with '&' parse safely."""
    lines = [BEGIN]
    for m in mapped:
        lines.append(f"  - {{symbol: {json.dumps(m.symbol)}, breeze_code: {json.dumps(m.breeze_code)}, "
                     f"kind: stock, sector: {json.dumps(m.sector)}}}")
    lines.append(END)
    return "\n".join(lines)


def replace_block(config_text: str, block: str) -> str:
    """Swap the generated block in config.yaml text. The markers must already exist once."""
    if config_text.count(BEGIN) != 1 or config_text.count(END) != 1:
        raise ValueError("config.yaml must contain the nifty50 BEGIN and END marker lines exactly once")
    a = config_text.index(BEGIN)
    b = config_text.index(END, a) + len(END)
    return config_text[:a] + block + config_text[b:]


def validate_config_text(text: str) -> Settings:
    """The new config must load cleanly before it is written."""
    return Settings.model_validate(yaml.safe_load(text))


def update_config(config_path: Path, constituents_text: str, scrip_rows: list[dict[str, str]],
                  write: bool = True) -> dict:
    """Steps 1 and 2 of a watchlist refresh. Returns a report; writes only if the result is valid."""
    old_text = config_path.read_bytes().decode("utf-8")      # keep the file's own line endings
    old = validate_config_text(old_text)
    constituents = read_constituents(constituents_text)
    mapped, unmapped = map_constituents(constituents, scrip_rows)
    if not mapped:
        raise ValueError("no symbol could be mapped; config.yaml not changed")
    nl = "\r\n" if "\r\n" in old_text else "\n"
    new_text = replace_block(old_text, render_block(mapped).replace("\n", nl))
    new = validate_config_text(new_text)
    old_codes = {i.symbol: i.breeze_code for i in old.watchlist}
    new_codes = {i.symbol: i.breeze_code for i in new.watchlist}
    report = {
        "constituents": len(constituents),
        "mapped": [(m.symbol, m.breeze_code, m.sector) for m in mapped],
        "unmapped": unmapped,
        "added": sorted(set(new_codes) - set(old_codes)),
        "removed": sorted(set(old_codes) - set(new_codes)),
        "code_changed": sorted((s, old_codes[s], new_codes[s]) for s in set(old_codes) & set(new_codes)
                               if old_codes[s] != new_codes[s]),
        "watchlist_size": len(new.watchlist),
        "written": False,
    }
    if write and new_text != old_text:
        config_path.write_bytes(new_text.encode("utf-8"))
        report["written"] = True
    return report
